-- Supabase schema for BTM project
-- Run this in Supabase SQL Editor

create extension if not exists pgcrypto;

create table if not exists profiles (
  id uuid primary key default gen_random_uuid(),
  email text unique not null,
  name text,
  role text not null default 'client',
  created_at timestamptz not null default now()
);

create table if not exists materials (
  id bigint generated by default as identity primary key,
  label text not null,
  unit text not null,
  unit_price numeric(10,2) not null default 0,
  category text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists labor_settings (
  id bigint generated by default as identity primary key,
  project_type text not null unique,
  daily_rate numeric(10,2) not null default 0,
  productivity numeric(10,2) not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists delivery_settings (
  id bigint generated by default as identity primary key,
  base_price numeric(10,2) not null default 0,
  per_tonne numeric(10,2) not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists suppliers (
  id bigint generated by default as identity primary key,
  name text not null,
  city text,
  phone text,
  email text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists projects (
  id bigint generated by default as identity primary key,
  user_id uuid references profiles(id) on delete set null,
  name text not null,
  project_type text not null,
  total_budget numeric(12,2) not null default 0,
  status text not null default 'draft',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists project_items (
  id bigint generated by default as identity primary key,
  project_id bigint references projects(id) on delete cascade,
  material_id bigint references materials(id) on delete set null,
  quantity numeric(12,2) not null default 0,
  unit_price numeric(10,2) not null default 0,
  total_price numeric(12,2) not null default 0,
  created_at timestamptz not null default now()
);

create or replace function update_updated_at_column()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

create trigger set_updated_at_materials
before update on materials
for each row execute procedure update_updated_at_column();

create trigger set_updated_at_labor_settings
before update on labor_settings
for each row execute procedure update_updated_at_column();

create trigger set_updated_at_delivery_settings
before update on delivery_settings
for each row execute procedure update_updated_at_column();

create trigger set_updated_at_projects
before update on projects
for each row execute procedure update_updated_at_column();

